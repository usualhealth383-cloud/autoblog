def norm(s):
    s = (s or '').lower().replace(' ', '')
    s = re.sub(r'[()\[\]{}<>,./|·+]', '', s)
    prev = None
    while prev != s:
        prev = s
        for t in SALT:
            if s.startswith(t) and len(s) > len(t) + 1: s = s[len(t):]
            if s.endswith(t) and len(s) > len(t) + 1: s = s[:-len(t)]
    return s

